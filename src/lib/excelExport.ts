import * as XLSX from 'xlsx';
import { InvoiceData } from '../types/invoice.js';

export function exportSingleInvoiceToExcel(invoice: InvoiceData): void {
  const wb = XLSX.utils.book_new();

  // Sheet 1: Invoice Overview & Cost Totals
  const overviewData: (string | number)[][] = [
    ['MANUFACTURING INVOICE RECORD & OCR EXTRACTION'],
    ['Generated by Manufacturing Invoice OCR System', '', 'Export Date:', new Date().toISOString().slice(0, 10)],
    [],
    ['GENERAL METADATA', ''],
    ['Invoice Number:', invoice.invoiceNumber || 'N/A', 'Invoice Date:', invoice.invoiceDate || 'N/A'],
    ['Purchase Order (PO) #:', invoice.poNumber || 'N/A', 'Due Date:', invoice.dueDate || 'N/A'],
    ['Delivery Challan / GRN:', invoice.deliveryChallan || 'N/A', 'Payment Terms:', invoice.paymentTerms || 'Net 30'],
    ['Payment Status:', (invoice.paymentStatus || 'pending').toUpperCase(), 'Category:', invoice.manufacturingCategory || 'raw_materials'],
    [],
    ['SUPPLIER / VENDOR DETAILS', ''],
    ['Vendor Name:', invoice.vendorName || 'Unknown Vendor'],
    ['Tax ID / GSTIN / VAT:', invoice.vendorTaxId || 'N/A'],
    ['Vendor Address:', invoice.vendorAddress || 'N/A'],
    ['Contact Info:', `${invoice.vendorPhone || ''} ${invoice.vendorEmail || ''}`.trim() || 'N/A'],
    [],
    ['BUYER / FACTORY ENTITY', ''],
    ['Customer / Plant:', invoice.customerName || 'Manufacturing Plant Unit'],
    ['Delivery Address:', invoice.customerAddress || 'N/A'],
    [],
    ['FINANCIAL COST BREAKDOWN', `(${invoice.currency || 'USD'})`],
    ['Material Subtotal (Net):', invoice.subtotal || 0],
    ['Freight & Logistics Charges:', invoice.freightCharge || 0],
    ['Taxes (GST / VAT / Sales Tax):', invoice.taxAmount || 0],
    ['Discounts / Deductions:', invoice.discount ? -invoice.discount : 0],
    ['---------------------------', '----------'],
    ['TOTAL COST PAYABLE (GRAND TOTAL):', invoice.grandTotal || 0],
    [],
    ['Notes / Terms:', invoice.notes || 'No special remarks recorded.'],
  ];

  const wsOverview = XLSX.utils.aoa_to_sheet(overviewData);
  // Column width styling
  wsOverview['!cols'] = [
    { wch: 32 },
    { wch: 35 },
    { wch: 22 },
    { wch: 25 },
  ];
  XLSX.utils.book_append_sheet(wb, wsOverview, 'Invoice Summary');

  // Sheet 2: Itemized Line Items Table
  if (invoice.lineItems && invoice.lineItems.length > 0) {
    const itemsHeaders = [
      'Line #',
      'Part / Item Code',
      'Material / Description',
      'Quantity',
      'Unit of Measure',
      `Unit Price (${invoice.currency})`,
      'Tax %',
      `Total Line Cost (${invoice.currency})`,
    ];

    const itemsRows = invoice.lineItems.map((item, index) => [
      index + 1,
      item.itemCode || '—',
      item.description || '',
      item.quantity || 0,
      item.unit || 'pcs',
      item.unitPrice || 0,
      item.taxPercent ? `${item.taxPercent}%` : '0%',
      item.totalPrice || (item.quantity * item.unitPrice),
    ]);

    // Summary footer row
    const totalQty = invoice.lineItems.reduce((acc, it) => acc + (it.quantity || 0), 0);
    const totalLineAmount = invoice.lineItems.reduce((acc, it) => acc + (it.totalPrice || 0), 0);
    itemsRows.push([
      'TOTAL',
      '',
      'All Materials Total',
      totalQty,
      '',
      '',
      '',
      totalLineAmount,
    ]);

    const wsItems = XLSX.utils.aoa_to_sheet([itemsHeaders, ...itemsRows]);
    wsItems['!cols'] = [
      { wch: 8 },
      { wch: 18 },
      { wch: 40 },
      { wch: 12 },
      { wch: 16 },
      { wch: 18 },
      { wch: 10 },
      { wch: 22 },
    ];
    XLSX.utils.book_append_sheet(wb, wsItems, 'Line Items');
  }

  const cleanVendor = (invoice.vendorName || 'Vendor').replace(/[^a-zA-Z0-9]/g, '_').slice(0, 20);
  const cleanInv = (invoice.invoiceNumber || 'INV').replace(/[^a-zA-Z0-9]/g, '_');
  const fileName = `Invoice_${cleanInv}_${cleanVendor}.xlsx`;

  XLSX.writeFile(wb, fileName);
}

export function exportInvoiceBatchToExcel(invoices: InvoiceData[], exportName: string = 'Manufacturing_Invoices_Register'): void {
  const wb = XLSX.utils.book_new();

  // 1. Invoices Register Sheet
  const registerHeaders = [
    'Invoice #',
    'Date',
    'Vendor Name',
    'Tax ID / GSTIN',
    'Category',
    'PO Number',
    'Challan / GRN',
    'Currency',
    'Subtotal',
    'Freight Charge',
    'Tax Amount',
    'Discount',
    'Total Cost (Payable)',
    'Payment Status',
    'Payment Terms',
    'Due Date',
  ];

  const registerRows = invoices.map((inv) => [
    inv.invoiceNumber,
    inv.invoiceDate,
    inv.vendorName,
    inv.vendorTaxId || '',
    inv.manufacturingCategory,
    inv.poNumber || '',
    inv.deliveryChallan || '',
    inv.currency || 'USD',
    inv.subtotal,
    inv.freightCharge,
    inv.taxAmount,
    inv.discount,
    inv.grandTotal,
    (inv.paymentStatus || 'pending').toUpperCase(),
    inv.paymentTerms || '',
    inv.dueDate || '',
  ]);

  const wsRegister = XLSX.utils.aoa_to_sheet([registerHeaders, ...registerRows]);
  wsRegister['!cols'] = [
    { wch: 16 },
    { wch: 12 },
    { wch: 28 },
    { wch: 18 },
    { wch: 18 },
    { wch: 14 },
    { wch: 16 },
    { wch: 10 },
    { wch: 14 },
    { wch: 14 },
    { wch: 14 },
    { wch: 12 },
    { wch: 18 },
    { wch: 16 },
    { wch: 14 },
    { wch: 12 },
  ];
  XLSX.utils.book_append_sheet(wb, wsRegister, 'Invoices Register');

  // 2. Consolidated Line Items Sheet
  const lineItemHeaders = [
    'Invoice #',
    'Vendor',
    'Date',
    'Item / Part #',
    'Description',
    'Quantity',
    'Unit',
    'Unit Price',
    'Line Total',
    'Currency',
  ];

  const consolidatedItems: (string | number)[][] = [];
  for (const inv of invoices) {
    if (inv.lineItems && inv.lineItems.length > 0) {
      for (const item of inv.lineItems) {
        consolidatedItems.push([
          inv.invoiceNumber,
          inv.vendorName,
          inv.invoiceDate,
          item.itemCode || '',
          item.description,
          item.quantity,
          item.unit,
          item.unitPrice,
          item.totalPrice,
          inv.currency || 'USD',
        ]);
      }
    }
  }

  if (consolidatedItems.length > 0) {
    const wsLineItems = XLSX.utils.aoa_to_sheet([lineItemHeaders, ...consolidatedItems]);
    wsLineItems['!cols'] = [
      { wch: 16 },
      { wch: 25 },
      { wch: 12 },
      { wch: 18 },
      { wch: 35 },
      { wch: 12 },
      { wch: 10 },
      { wch: 14 },
      { wch: 16 },
      { wch: 10 },
    ];
    XLSX.utils.book_append_sheet(wb, wsLineItems, 'All Line Items');
  }

  // 3. Vendor Summary Sheet
  const vendorMap = new Map<string, { count: number; spend: number; currency: string }>();
  for (const inv of invoices) {
    const key = inv.vendorName || 'Unknown Vendor';
    const curr = vendorMap.get(key) || { count: 0, spend: 0, currency: inv.currency || 'USD' };
    curr.count += 1;
    curr.spend += inv.grandTotal || 0;
    vendorMap.set(key, curr);
  }

  const vendorHeaders = ['Vendor / Supplier Name', 'Invoices Count', 'Total Spend', 'Currency'];
  const vendorRows = Array.from(vendorMap.entries()).map(([vendor, data]) => [
    vendor,
    data.count,
    data.spend,
    data.currency,
  ]);

  const wsVendors = XLSX.utils.aoa_to_sheet([vendorHeaders, ...vendorRows]);
  wsVendors['!cols'] = [
    { wch: 32 },
    { wch: 16 },
    { wch: 18 },
    { wch: 12 },
  ];
  XLSX.utils.book_append_sheet(wb, wsVendors, 'Vendor Spend Summary');

  const dateStr = new Date().toISOString().slice(0, 10);
  XLSX.writeFile(wb, `${exportName}_${dateStr}.xlsx`);
}
